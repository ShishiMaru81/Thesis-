"""
refs_spec.py — the thesis bibliography, one dict per reference.

Fields
  key        citation key used in the chapters
  title      expected title (checked against the fetched record)
  doi / arxiv / acl / url / openalex / venue   where the record is fetched from
  claim      what the thesis cites the work for
  evidence   phrases that must occur in the fetched abstract, title or page text;
             each was read in the source before being recorded here
  title_only True when the source record has no abstract: the check is then that
             the title, authors, year and venue match, which is adequate only for
             citing the original publication of a method or a resource by name
  bibtype + bib   hand-written entry for sources without a machine record
  add        extra BibLaTeX fields appended to a fetched record
"""
VERIFIED_ON = "2026-09-24"

NIPS = "Advances in Neural Information Processing Systems (NeurIPS)"
ICLR = "International Conference on Learning Representations (ICLR)"


def neurips(year: str) -> dict:
    return dict(kind="listing", url=f"https://proceedings.neurips.cc/paper_files/paper/{year}",
                expect=f"NeurIPS {year} proceedings index", booktitle=NIPS, year=year)


def openreview(term: str, year: str, api: str = "api") -> dict:
    import urllib.parse
    return dict(kind="openreview", url=f"https://{api}.openreview.net/notes/search?term={urllib.parse.quote(term)}"
                f"&group=ICLR.cc/{year}/Conference&source=forum", expect=f"ICLR {year}", booktitle=ICLR, year=year)


