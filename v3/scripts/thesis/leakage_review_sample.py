#!/usr/bin/env python3
"""
leakage_review_sample.py — 60-pair review sheet for the semantic leakage detector (Stage 3, detector 3).

The detector passed with 794 candidate pairs (cosine >= 0.92) and no human decision
recorded. This script draws a fixed-seed sample of 60 pairs for two reviewers to
label independently as 'leakage' or 'legitimate'.

Sampling frame: the pairs stored in reports/leakage/leakage_report.json, i.e. the
100 highest-cosine candidates plus the first 50 pending pairs in discovery order
(duplicates removed). The full list of 794 is not stored, and rebuilding it would
mean reading the training corpus, which thesis scripts never open. The frame is
therefore weighted towards the most similar pairs; this is stated in the thesis.

Writes (new files only; nothing existing is modified):
  reports/leakage/review/semantic_review_sample.csv   (UTF-8 with BOM, opens in Excel)
  reports/leakage/review/README.md
"""
from __future__ import annotations

import csv
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORT = ROOT / "reports" / "leakage" / "leakage_report.json"
OUT = ROOT / "reports" / "leakage" / "review"
N = 60
SEED = 42


def main() -> None:
    d3 = json.loads(REPORT.read_text(encoding="utf-8"))["detector_3_semantic"]
    frame: dict[str, dict] = {}
    for rec in d3["candidates"] + d3["pending_review"]:
        frame.setdefault(rec["pair_key"], rec)
    keys = sorted(frame)
    rng = random.Random(SEED)
    sample = sorted(rng.sample(keys, N), key=lambda k: -frame[k]["cosine"])
    OUT.mkdir(parents=True, exist_ok=True)
    cols = ["sample_id", "pair_key", "held_out_split", "held_out_row_id", "train_row_id", "lang", "qtype", "cosine",
            "same_fact_id", "held_out_question", "train_question", "reviewer_1_decision", "reviewer_1_note",
            "reviewer_2_decision", "reviewer_2_note"]
    with (OUT / "semantic_review_sample.csv").open("w", encoding="utf-8-sig", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for i, k in enumerate(sample, 1):
            r = frame[k]
            w.writerow({"sample_id": f"S{i:02d}", "pair_key": k, "held_out_split": r["held_out_split"],
                        "held_out_row_id": r["held_out_row_id"], "train_row_id": r["train_row_id"], "lang": r["lang"],
                        "qtype": r["qtype"], "cosine": f"{r['cosine']:.6f}", "same_fact_id": r["same_fact_id"],
                        "held_out_question": r["held_out_question"], "train_question": r["train_question"],
                        "reviewer_1_decision": "", "reviewer_1_note": "", "reviewer_2_decision": "", "reviewer_2_note": ""})
    cos = [frame[k]["cosine"] for k in sample]
    readme = f"""# Semantic leakage review sample

`semantic_review_sample.csv` holds {N} pairs drawn with `random.Random({SEED})` from the {len(keys)} distinct
pairs stored in `reports/leakage/leakage_report.json` (detector 3: the 100 highest-cosine candidates plus the
first 50 pending pairs). The detector found {d3['n_candidates_at_or_above_threshold']} pairs at cosine >= {d3['threshold']};
the full list is not stored, so this sample over-represents the most similar pairs
(cosine in this sample: {min(cos):.3f} to {max(cos):.3f}).

Two reviewers label every row **independently**, without seeing each other's sheet.

* `leakage`: the held-out question asks for the same fact as the training question (same crop, same
  stage or attribute, same expected answer), only reworded or translated.
* `legitimate`: the two questions share a template but ask about a different crop, stage, attribute or
  scenario, so knowing one answer does not give the other.

Write the decision in `reviewer_N_decision` (exactly `leakage` or `legitimate`) and anything unclear in
`reviewer_N_note`. Do not edit any other column. Generated by `scripts/thesis/leakage_review_sample.py`.
"""
    (OUT / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    print(f"wrote {N} pairs from a frame of {len(keys)} -> {OUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
