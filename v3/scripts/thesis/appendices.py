"""Generate appendix tables B (per-seed), C (per-category) and G (hashes).

Read-only on upstream artefacts. Writes only under thesis/generated/tables/.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / "thesis" / "generated" / "tables"
SM = ROOT / "reports" / "s6" / "summary_by_arm.csv"
CAT = ROOT / "reports" / "s6" / "per_category.csv"
VER = ROOT / "thesis" / "generated" / "adapter_verification.json"
TEST_SHA = ROOT / "data" / "hardened" / "test_hardened.sha256"
SEED_SHA = ROOT / "data" / "splits" / "test.sha256"

ORDER = [
    "llama31_8b_zeroshot",
    "llama31_8b_seed42", "llama31_8b_seed1337", "llama31_8b_seed2024", "llama31_8b_seed42_clarify",
    "mistral_nemo_zeroshot",
    "mistral_nemo_seed42", "mistral_nemo_seed1337", "mistral_nemo_seed2024", "mistral_nemo_seed42_clarify",
    "phi35_mini_zeroshot",
    "phi35_mini_seed42", "phi35_mini_seed1337", "phi35_mini_seed2024", "phi35_mini_seed42_clarify",
    "phi4_mini_zeroshot",
    "phi4_mini_seed42", "phi4_mini_seed1337", "phi4_mini_seed2024", "phi4_mini_seed42_clarify",
]
SHORT = {
    "llama31_8b": "Llama-3.1-8B", "mistral_nemo": "Mistral-NeMo-12B",
    "phi35_mini": "Phi-3.5-mini", "phi4_mini": "Phi-4-mini",
}
CATS = ["seed", "code_switched", "misspelled_crop", "unit_ambiguity", "missing_parameter", "multi_crop"]


def pct(x: float) -> str:
    """summary_by_arm.csv and per_category.csv already store these as percents (0–100)."""
    return f"{float(x):.1f}"


def wrap(name: str, caption: str, label: str, colspec: str, header: str, body: str, size: str = r"\scriptsize") -> str:
    return (
        "% AUTO-GENERATED by scripts/thesis/appendices.py\n"
        "\\begin{table}[tbp]\n\\centering\n"
        f"{size}\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        f"\\begin{{tabular}}{{{colspec}}}\n\\toprule\n"
        f"{header} \\\\\n\\midrule\n{body}\\bottomrule\n"
        "\\end{tabular}\n\\end{table}\n"
    )


def tb() -> None:
    sm = pd.read_csv(SM).set_index("arm")
    rows = []
    for arm in ORDER:
        r = sm.loc[arm]
        model = SHORT[arm.split("_seed")[0].replace("_zeroshot", "") if "zeroshot" in arm else
                      "_".join(arm.split("_")[:2]) if arm.startswith("phi") else
                      "_".join(arm.split("_")[:2])]
        # more reliable parse
        if arm.startswith("llama31"):
            model = "Llama-3.1-8B"
        elif arm.startswith("mistral"):
            model = "Mistral-NeMo"
        elif arm.startswith("phi35"):
            model = "Phi-3.5-mini"
        elif arm.startswith("phi4"):
            model = "Phi-4-mini"
        if "zeroshot" in arm:
            var = "zero-shot"
        elif "clarify" in arm:
            var = "CL 42"
        elif "seed42" in arm:
            var = "FT 42"
        elif "seed1337" in arm:
            var = "FT 1337"
        else:
            var = "FT 2024"
        rows.append(
            f"{model} & {var} & {pct(r.exact_numeric_0p1)} & {pct(r.exact_clarify)} & "
            f"{pct(r.invented_value_rate)} & {pct(r.abstain_accuracy)} & {r.chrf_pp:.1f} \\\\"
        )
    body = "\n".join(rows) + "\n"
    text = wrap(
        "tb_per_seed",
        r"Per-arm headline scores on the locked test set (one evaluation run each). "
        r"Numeric: share of \NumericSingle{} single-crop rows within $\pm$0.1\,mm. "
        r"Clarify exact and invented value: \TestClarify{} rows. Abstain: \TestAbstain{} seed out-of-domain rows. "
        r"chrF++: \TestFactual{} factual rows. Source: \texttt{reports/s6/summary\_by\_arm.csv}.",
        "tab:per-seed",
        "llrrrrr",
        r"Model & Arm & $\pm$0.1 mm (\%) & Clarify exact (\%) & Invented (\%) & Abstain (\%) & chrF++",
        body,
    )
    (GEN / "tb_per_seed.tex").write_text(text, encoding="utf-8", newline="\n")


def tc() -> None:
    cat = pd.read_csv(CAT)
    arms = [
        ("llama31_8b_zeroshot", "Llama ZS"),
        ("llama31_8b_seed42", "Llama FT 42"),
        ("llama31_8b_seed42_clarify", "Llama CL 42"),
        ("mistral_nemo_seed42", "Mistral FT 42"),
    ]
    rows = []
    for arm, lab in arms:
        sub = cat[cat.arm == arm].set_index("category")
        for c in CATS:
            if c not in sub.index:
                continue
            r = sub.loc[c]
            em = "" if pd.isna(r.exact_numeric_0p1) else f"{float(r.exact_numeric_0p1):.1f}"
            cl = "" if pd.isna(r.exact_clarify) else f"{float(r.exact_clarify):.1f}"
            inv = "" if pd.isna(r.invented_value_rate) else f"{float(r.invented_value_rate):.1f}"
            ab = "" if pd.isna(r.abstain_accuracy) else f"{float(r.abstain_accuracy):.1f}"
            rows.append(
                f"{lab} & {c.replace('_', ' ')} & {int(r.n_scored)} & {em} & {cl} & {inv} & {ab} \\\\"
            )
    body = "\n".join(rows) + "\n"
    text = wrap(
        "tc_per_category",
        r"Per-category scores for the four human-study arms (and Llama zero-shot). "
        r"Numeric exact-0.1 is the share of that category's numeric rows within $\pm$0.1\,mm; "
        r"blank cells are not defined for that category. "
        r"Source: \texttt{reports/s6/per\_category.csv}. The \TestExcludedOOD{} adversarial out-of-domain "
        r"and \TestExcludedConflict{} conflicting-value rows are excluded from scoring and do not appear.",
        "tab:per-category",
        "llrrrrr",
        r"Arm & Category & $n$ & $\pm$0.1 mm (\%) & Clarify exact (\%) & Invented (\%) & Abstain (\%)",
        body,
    )
    (GEN / "tc_per_category.tex").write_text(text, encoding="utf-8", newline="\n")


def file_sha(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def tg() -> None:
    test = TEST_SHA.read_text(encoding="utf-8").split()[0]
    seed = SEED_SHA.read_text(encoding="utf-8").split()[0]
    ver = json.loads(VER.read_text(encoding="utf-8"))
    rows = [
        r"\texttt{data/hardened/test\_hardened.jsonl} & locked test set & "
        + test[:12] + r"\ldots & recorded in \texttt{test\_hardened.sha256} \\",
        r"\texttt{data/splits/test.jsonl} & seed test split & "
        + seed[:12] + r"\ldots & recorded in \texttt{test.sha256} \\",
    ]
    for arm in ver["arms"]:
        if not arm.get("sha256_on_disk"):
            continue
        sha = arm["sha256_on_disk"]
        match = all(rec.get("match") for rec in arm.get("records", {}).values()) if arm.get("records") else True
        rows.append(
            f"\\texttt{{{arm['arm'].replace('_', '\\_')}}} & adapter & {sha[:12]}\\ldots & "
            + ("matches manifest" if match else "MISMATCH") + r" \\"
        )
    body = "\n".join(rows) + "\n"
    text = wrap(
        "tg_hashes",
        r"SHA-256 prefixes (first 12 hex characters) of the locked test files and of every adapter "
        r"loaded at evaluation. Full digests are in the \texttt{.sha256} sidecars and in "
        r"\texttt{thesis/generated/adapter\_verification.json}. All "
        + str(ver["n_adapter_pass"]) + r" adapter arms matched their training manifests.",
        "tab:hashes",
        r"lll>{\raggedright\arraybackslash}p{0.28\textwidth}",
        r"File / arm & What & SHA-256 prefix & Check",
        body,
        size=r"\footnotesize",
    )
    (GEN / "tg_hashes.tex").write_text(text, encoding="utf-8", newline="\n")


def main() -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    tb()
    tc()
    tg()
    print("wrote", GEN / "tb_per_seed.tex")
    print("wrote", GEN / "tc_per_category.tex")
    print("wrote", GEN / "tg_hashes.tex")


if __name__ == "__main__":
    main()
